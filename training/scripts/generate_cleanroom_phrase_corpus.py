"""Generate deterministic multi-note clean-room bowed-string phrase supervision.

All score/control material and rendered audio are generated by SONICRAFT's
independently authored physical teacher. No third-party model, audio, preset,
checkpoint, or hidden metadata is consumed.
"""
import argparse
